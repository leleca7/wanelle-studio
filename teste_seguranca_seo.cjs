'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const api=fs.readFileSync('api/wanelle.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const admin=fs.readFileSync('admin.html','utf8');
const reset=fs.readFileSync('redefinir-senha.html','utf8');
const headers=JSON.parse(fs.readFileSync('vercel.json','utf8')).headers;
const headerMap=Object.fromEntries(headers.flatMap(x=>x.headers.map(h=>[h.key,h.value])));
assert.match(api,/await authorized\(sql,req\);\s*if\(req\.method==='GET'&&action==='bootstrap'\)/,'bootstrap must require authorization');
assert.match(api,/await authorized\(sql,req\);\s*if\(req\.method==='POST'&&action==='section'\)/,'section writes must require authorization');
assert.match(api,/await authorized\(sql,req\);\s*if\(req\.method==='POST'&&action==='order'\)/,'order writes must require authorization');
assert.match(api,/await authorized\(sql,req\);\s*if\(req\.method==='POST'&&action==='delete'\)/,'order deletes must require authorization');
assert.match(api,/revoked_before=clock_timestamp\(\)/,'logout must revoke server-side sessions');
assert.match(api,/SELECT changed_at,revoked_before FROM public\.wanelle_password_recovery/,'auth must check server-side revocation');
assert.match(api,/HttpOnly; Secure; SameSite=Strict/,'session cookie flags must remain hardened');
assert.match(api,/locked_until/,'login throttling must remain');
assert.match(api,/body\.privacyAccepted!==true/,'public intake must require explicit privacy acknowledgement');
assert.match(index,/<link rel="canonical" href="https:\/\/wanelle-site\.vercel\.app\/">/,'canonical must point to production home');
assert.match(index,/og:title/,'Open Graph title must exist');
assert.match(index,/"@type":"Bakery"/,'structured data must identify the bakery without fabricated address/reviews');
assert.match(admin,/name="robots" content="noindex, nofollow, noarchive"/,'admin page must be noindex');
assert.match(reset,/name="robots" content="noindex"/,'password reset page must be noindex');
assert.match(headerMap['Content-Security-Policy']||'',/default-src 'self'/,'CSP must be present');
assert.match(headerMap['Content-Security-Policy']||'',/object-src 'none'/,'CSP must disable plugins');
assert.match(headerMap['X-Frame-Options']||'','DENY','framing protection must remain');
assert.ok(fs.existsSync('robots.txt'),'robots.txt must exist');
assert.ok(fs.existsSync('sitemap.xml'),'sitemap.xml must exist');
assert.ok(fs.existsSync('privacidade.html'),'privacy policy must exist');
assert.ok(!fs.existsSync('assets/market-prices.json'),'private market quotes must not ship as a public static JSON asset');
assert.ok(!fs.existsSync('assets/market-prices.js'),'private market quotes must not ship as a public static JS asset');
console.log('Security/SEO regression checks passed (static checks only; not a substitute for live API/browser integration tests).');
